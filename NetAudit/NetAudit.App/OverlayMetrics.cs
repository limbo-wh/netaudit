namespace NetAudit.App;

/// <summary>
/// Единый список метрик оверлея — ключ, подпись, порядок по умолчанию. Общий источник
/// для настроек (порядок и видимость хранятся по этим ключам), окна настроек (список
/// для перетаскивания) и самого оверлея (какие строки существуют и в каком порядке
/// они идут, пока пользователь ничего не передвигал).
/// </summary>
public static class OverlayMetrics
{
    public static readonly (string Key, string Label, string Tooltip)[] Catalog =
    [
        ("Fps",     "Кадры (FPS)",
            "Первая строка оверлея. Кадры считаются по событиям Windows (ETW), без вмешательства " +
            "в процесс игры — но для этого нужны права администратора. Без них строка показывает прочерк."),
        ("Cpu",     "Процессор (%)", "Загрузка процессора."),
        ("Gpu",     "Видеокарта (%)", "Загрузка GPU (Performance Counters)."),
        ("CpuTemp", "Темп. CPU (°C)",
            "Температура процессора. Нужны права администратора — драйвер датчиков без них не встаёт, строка покажет прочерк."),
        ("GpuTemp", "Темп. GPU (°C)", "Температура видеокарты. Тоже требует прав администратора."),
        ("Ram",     "Память (ГБ)", "Используемое ОЗУ."),
        ("NetRx",   "↓ Приём (МБ/с)", "Входящий трафик."),
        ("NetTx",   "↑ Отдача (МБ/с)", "Исходящий трафик."),
        ("GwPing",  "Шлюз (мс)", "Задержка до роутера."),
        ("GwLoss",  "Потери до шлюза (%)",
            "Доля потерянных пакетов до роутера за сессию. Растёт — виноват Wi-Fi, кабель или роутер."),
        ("CfPing",  "Интернет (мс)", "Задержка до Cloudflare."),
        ("CfLoss",  "Потери до сети (%)",
            "Доля потерянных пакетов до 1.1.1.1 за сессию. Растёт при целом шлюзе — виноват провайдер."),
    ];

    public static List<string> DefaultOrder() => [.. Catalog.Select(c => c.Key)];

    /// <summary>
    /// Чинит сохранённый порядок: неизвестные ключи (например, из будущей версии, если
    /// пользователь откатится) выкидывает, пропущенные (старый settings.json без этого
    /// поля вовсе, или новая метрика, которой ещё не было на момент сохранения) дописывает
    /// в конец в порядке по умолчанию — иначе такая строка просто не нашла бы себе места.
    /// </summary>
    public static List<string> Normalize(List<string>? order)
    {
        var known = new HashSet<string>(Catalog.Select(c => c.Key));
        var result = new List<string>();

        if (order is not null)
            foreach (var key in order)
                if (known.Contains(key) && !result.Contains(key))
                    result.Add(key);

        foreach (var (key, _, _) in Catalog)
            if (!result.Contains(key))
                result.Add(key);

        return result;
    }
}
